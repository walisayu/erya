#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
文件↔程式碼對應表工具。

    python3 scripts/doc_source_map.py gen     # 重新產生對應表，並把目前 commit 記成快照
    python3 scripts/doc_source_map.py check   # 列出快照之後動過的程式檔與該重看的章節

對應表寫在 docs/manual/文件對應程式碼.md，是自動產生的，不要手改。
"""
from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import build  # noqa: E402

LANG = build.load_language("en")

ROOT = Path(__file__).resolve().parent.parent          # docs/manual
REPO = ROOT.parent.parent                              # Source 目錄
TABLE = ROOT / "DocumentCodeMap.md"

# 章號 → 這一章描述的程式碼來源。綜整章沒有專屬來源檔。
SOURCES = {
    "1.1": ["README.zh-TW.md", "src/lib.rs"],
    "1.2": ["src/main.rs", "src/terminal.rs", "README.zh-TW.md"],
    "1.3": ["src/terminal.rs", "src/editor.rs"],
    "2.1": ["src/workspace.rs", "src/file_browser.rs", "src/document.rs"],
    "2.2": ["src/editor.rs", "src/layout.rs"],
    "2.3": ["src/editor.rs"],
    "2.4": ["src/editor.rs", "src/automation.rs"],
    "3.1": ["src/document.rs", "src/syntax.rs", "src/formatter.rs"],
    "3.2": ["src/large_file.rs", "src/document.rs"],
    "3.3": ["src/hex.rs", "src/binary.rs"],
    "3.4": ["src/comparison.rs"],
    "4.1": ["src/keymap.rs", "keymap/"],
    "4.2": ["src/i18n.rs", "locales/"],
    "4.3": [],
    "4.4": ["src/keymap.rs", "locales/zh-TW.toml"],
    "gotchas": [],
}


def git(*args: str) -> str:
    return subprocess.run(
        ["git", *args], cwd=REPO, capture_output=True, text=True, check=True
    ).stdout.strip()


def current_commit() -> str:
    return git("rev-parse", "--short", "HEAD")


def snapshot_from_table() -> str | None:
    if not TABLE.exists():
        return None
    found = re.search(r"Snapshot commit: `([0-9a-f]+)`", TABLE.read_text(encoding="utf-8"))
    return found.group(1) if found else None


def gen() -> None:
    commit = current_commit()
    date = git("show", "-s", "--format=%cs", "HEAD")
    lines = [
        "# Documentation-to-code mapping",
        "",
        "**Generated by `scripts/doc_source_map.py gen`; do not edit by hand.**",
        "",
        f"Snapshot commit: `{commit}` ({date})",
        "",
        "Each chapter describes the source files below. Review the corresponding chapters when a file changes.",
        "Run `python3 scripts/doc_source_map.py check` to list the chapters to review.",
        "",
        "| Chapter | Title | Source files |",
        "| --- | --- | --- |",
    ]
    for chapter in LANG.CHAPTERS:
        sources = SOURCES.get(chapter.no)
        if sources is None:
            raise SystemExit(f"SOURCES is missing chapter {chapter.no}; add it before generating the mapping")
        cell = ", ".join(f"`{s}`" for s in sources) if sources else "Overview chapter; no dedicated source files"
        lines.append(f"| {chapter.no} | {chapter.nav} | {cell} |")
    lines += [
        "",
        "## Outside the user manual",
        "",
        "- Release procedures (`build-release.sh`, `publish.sh`, `release-*.sh`) belong to maintainer documentation.",
        "- Tests and E2E specifications (`tests/`, `docs/e2e/`) are also outside the user manual.",
        "",
    ]
    TABLE.write_text("\n".join(lines), encoding="utf-8")
    print(f"Generated {TABLE.relative_to(ROOT)} (snapshot {commit})")


def check() -> None:
    snapshot = snapshot_from_table()
    if snapshot is None:
        raise SystemExit("Mapping is missing; run gen first")
    changed = [
        line for line in git("diff", "--relative", "--name-only", f"{snapshot}..HEAD").splitlines() if line
    ]
    if not changed:
        print(f"No changes since snapshot {snapshot}")
        return

    print(f"Snapshot {snapshot} → HEAD: {len(changed)} changed files\n")
    hits: dict[str, list[str]] = {}
    for chapter in LANG.CHAPTERS:
        for source in SOURCES.get(chapter.no, []):
            for path in changed:
                if path == source or (source.endswith("/") and path.startswith(source)):
                    hits.setdefault(f"{chapter.no} {chapter.nav}", []).append(path)
    if not hits:
        print("Changed files are outside the manual source list; no chapters need review.")
        return
    print("Chapters to review:")
    for chapter, paths in hits.items():
        unique = ", ".join(sorted(set(paths)))
        print(f"  {chapter}　←　{unique}")


def main() -> None:
    command = sys.argv[1] if len(sys.argv) > 1 else ""
    if command == "gen":
        gen()
    elif command == "check":
        check()
    else:
        raise SystemExit("Usage: doc_source_map.py gen|check")


if __name__ == "__main__":
    main()
